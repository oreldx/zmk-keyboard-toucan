def read_png(path):
    """Lit pixels of a non-interlaced 8-bit-or-less PNG, as rows of bools."""
    data = path.read_bytes()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError(f"{path.name}: not a PNG")
    pos, idat, palette, trns = 8, b"", None, None
    while pos < len(data):
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + length]
        if kind == b"IHDR":
            w, h, depth, color, _, _, interlace = struct.unpack(">IIBBBBB", body)
        elif kind == b"PLTE":
            palette = [tuple(body[i:i + 3]) for i in range(0, len(body), 3)]
        elif kind == b"tRNS":
            trns = body
        elif kind == b"IDAT":
            idat += body
        pos += 12 + length
    if interlace or depth > 8:
        raise ValueError(f"{path.name}: use a non-interlaced PNG with 8 bits per channel or less")
    channels = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[color]
    bpp = max(1, channels * depth // 8)
    stride = (w * channels * depth + 7) // 8
    raw, rows, prev = zlib.decompress(idat), [], bytearray(stride)
    for y in range(h):
        filt, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - bpp] if i >= bpp else 0
            b, c = prev[i], prev[i - bpp] if i >= bpp else 0
            if filt == 1:
                line[i] = (line[i] + a) & 0xFF
            elif filt == 2:
                line[i] = (line[i] + b) & 0xFF
            elif filt == 3:
                line[i] = (line[i] + (a + b) // 2) & 0xFF
            elif filt == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 0xFF
        prev = line
        if depth < 8:
            per_byte, mask = 8 // depth, (1 << depth) - 1
            samples = [(line[x // per_byte] >> (8 - depth * (x % per_byte + 1))) & mask for x in range(w)]
        else:
            samples = list(line)
        row = []
        for x in range(w):
            if color == 3:
                r, g, b_ = palette[samples[x]]
                alpha = trns[samples[x]] if trns and samples[x] < len(trns) else 255
            else:
                px = samples[x * channels:(x + 1) * channels]
                scale = 255 // ((1 << depth) - 1)
                r = g = b_ = px[0] * scale
                if color in (2, 6):
                    r, g, b_ = px[0], px[1], px[2]
                alpha = px[-1] if color in (4, 6) else 255
            row.append(alpha >= 128 and (r * 299 + g * 587 + b_ * 114) // 1000 >= 128)
        rows.append(row)
    return rows, w, h


def c_image(name, rows):
    """C source of a cropped LV_IMG_CF_INDEXED_1BIT image and its screen position."""
    lit = [(x, y) for y, row in enumerate(rows) for x, on in enumerate(row) if on]
    x0, x1 = min(x for x, _ in lit), max(x for x, _ in lit)
    y0, y1 = min(y for _, y in lit), max(y for _, y in lit)
    w, h = x1 - x0 + 1, y1 - y0 + 1
    data = []
    for y in range(y0, y1 + 1):
        for bx in range(x0, x1 + 1, 8):
            byte = 0
            for i in range(8):
                byte = (byte << 1) | (1 if bx + i <= x1 and rows[y][bx + i] else 0)
            data.append(byte)
    lines = ["    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + "," for i in range(0, len(data), 16)]
    src = (f"static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t {name}_map[] = {{\n"
           "    0x00, 0x00, 0x00, 0xff, /*Color of index 0*/\n"
           "    0xff, 0xff, 0xff, 0xff, /*Color of index 1*/\n"
           + "\n".join(lines) + "\n};\n\n"
           f"static const lv_img_dsc_t {name} = {{\n"
           "    .header.cf = LV_IMG_CF_INDEXED_1BIT,\n"
           "    .header.always_zero = 0,\n"
           "    .header.reserved = 0,\n"
           f"    .header.w = {w},\n"
           f"    .header.h = {h},\n"
           f"    .data_size = {8 + len(data)},\n"
           f"    .data = {name}_map,\n"
           "};\n")
    return src, x0, ORIGIN_Y + y0


def main():
    out = [LICENSE, "#include <lvgl.h>\n\n#include \"../widgets/bongo_cat.h\"\n"]
    for variant in VARIANTS:
        sprites = []
        for frame, index in FRAMES:
            path = HERE / f"{variant}_{frame}.png"
            rows, w, h = read_png(path)
            if (w, h) != (WIDTH, HEIGHT):
                raise ValueError(f"{path.name}: expected {WIDTH}x{HEIGHT}, got {w}x{h}")
            name = f"bongo_cat_{variant}_{frame}"
            src, x, y = c_image(name, rows)
            out.append(src)
            sprites.append(f"        [{index}] = {{&{name}, {x}, {y}}},")
        out.append(f"const struct bongo_cat_variant bongo_cat_variant_{variant} = {{\n"
                   "    .frames = {\n" + "\n".join(sprites) + "\n    },\n};\n")
    OUTPUT.write_text("\n".join(out))
    print(f"wrote {OUTPUT.relative_to(HERE.parent.parent)}")


if __name__ == "__main__":
    main()
